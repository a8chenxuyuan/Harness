-- ============================================================================
-- session_messages.status 新增 cancelled 语义（2026-11-26）
--
-- 背景：W2-PLAT-01 支持用户在流式生成过程中主动停止。
--       停止后消息保留已生成内容，状态记为 cancelled（区别于模型异常 failed），
--       前端据此展示「已取消」并允许重试 / 分支。
--
-- 变更：仅覆盖 status 列注释，不改表结构（VARCHAR(16) 已可容纳）。
--
-- 幂等：COMMENT 覆盖写，可重复执行。
--
-- 适用：PostgreSQL（SQLite 开发库无列注释概念，无需执行）。
-- ============================================================================

COMMENT ON COLUMN session_messages.status IS
    '消息状态：streaming 生成中 / completed 完成 / failed 失败 / cancelled 用户取消';


-- ---------------------------------------------------------------------------
-- 核对：注释已更新
-- ---------------------------------------------------------------------------
SELECT col_description(c.oid, a.attnum) AS status_comment
FROM pg_class c
JOIN pg_attribute a ON a.attrelid = c.oid AND a.attname = 'status'
WHERE c.relname = 'session_messages';


